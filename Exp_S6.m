%% Local functions
function configurations = define_s6_configurations( ...
    default_config, parameter_values)

    expected_count = 17;
    configurations = repmat(default_config, expected_count, 1);
    configuration_count = 1;
    specifications = { ...
        'lambda_min', 'lambda_min', 'Lambda min'; ...
        'lambda_max', 'lambda_max', 'Lambda max'; ...
        'huber', 'huber_scale_multiplier', 'Huber multiplier'; ...
        'alpha', 'grad_ema_alpha', 'Alpha'; ...
        'theta', 'side_threshold_multiplier', 'Theta multiplier'; ...
        'mu', 'mu', 'Mu'; ...
        'rank', 'estimated_rank', 'Estimated rank'; ...
        'irls', 'irls_max_iters', 'IRLS iterations'};

    for specification_index = 1:size(specifications, 1)
        family = specifications{specification_index, 1};
        field = specifications{specification_index, 2};
        label_prefix = specifications{specification_index, 3};
        values = parameter_values.(field);
        default_value = default_config.(field);

        for value_index = 1:numel(values)
            value = values(value_index);
            if abs(value - default_value) <= ...
                    10 * eps(max(1, abs(default_value)))
                continue;
            end
            id = [family, '_', numeric_identifier(value)];
            label = sprintf('%s %.4g', label_prefix, value);
            configuration_count = configuration_count + 1;
            configurations(configuration_count) = changed_configuration( ...
                default_config, id, label, family, value, field, value);
        end
    end

    configurations = configurations(1:configuration_count);
    configuration_ids = {configurations.id};
    if numel(configurations) ~= expected_count || ...
            numel(unique(configuration_ids)) ~= numel(configurations)
        error('Exp_S6:InvalidConfigurationSet', ...
            'S6 must contain 17 unique parameter configurations.');
    end
end

function identifier = numeric_identifier(value)
    identifier = sprintf('%.4g', value);
    identifier = strrep(identifier, '-', 'm');
    identifier = strrep(identifier, '+', '');
    identifier = strrep(identifier, '.', 'p');
end

function configuration = changed_configuration( ...
    default_config, id, label, family, parameter_value, field, value)

    configuration = default_config;
    configuration.id = id;
    configuration.label = label;
    configuration.parameter_family = family;
    configuration.parameter_value = parameter_value;
    configuration.(field) = value;
end

function seeds = make_s6_seeds(trial_seed)
    seeds.subspace = 100000 + trial_seed;
    seeds.temporal = 200000 + trial_seed;
    seeds.gaussian = 300000 + trial_seed;
    seeds.spatter = 400000 + trial_seed;
    seeds.observation = 500000 + trial_seed;
    seeds.side_delay = 600000 + trial_seed;
    seeds.side_noise = 700000 + trial_seed;
    seeds.initialization = 800000 + trial_seed;
    seeds.execution_order = 900000 + trial_seed;
end

function trial_data = generate_s6_trial( ...
    settings, seeds, max_estimated_rank)

    rows = settings.tensor_dims(1);
    cols = settings.tensor_dims(2);
    total_frames = settings.tensor_dims(3);
    true_rank = settings.true_rank;

    stream = RandStream('mt19937ar', 'Seed', seeds.subspace);
    basis_a_before = orthonormalize_with_sign( ...
        randn(stream, rows, true_rank));
    basis_b_before = orthonormalize_with_sign( ...
        randn(stream, cols, true_rank));
    basis_a_after = orthonormalize_with_sign( ...
        basis_a_before + settings.mutation_scale * ...
        randn(stream, rows, true_rank));
    basis_b_after = orthonormalize_with_sign( ...
        basis_b_before + settings.mutation_scale * ...
        randn(stream, cols, true_rank));

    stream = RandStream('mt19937ar', 'Seed', seeds.temporal);
    frame_axis = (1:total_frames)';
    temporal_coefficients = zeros(total_frames, true_rank);
    for component = 1:true_rank
        temporal_coefficients(:, component) = 10.0 + ...
            2.0 * sin(2 * pi * frame_axis / ...
            (100 + 10 * component)) + ...
            0.1 * randn(stream, total_frames, 1);
    end

    clean_tensor = zeros(rows, cols, total_frames);
    for frame = 1:total_frames
        if frame < settings.transition_boundary
            basis_a = basis_a_before;
            basis_b = basis_b_before;
        else
            basis_a = basis_a_after;
            basis_b = basis_b_after;
        end
        clean_tensor(:, :, frame) = basis_a * ...
            diag(temporal_coefficients(frame, :)) * basis_b';
    end

    signal_power = norm(clean_tensor(:))^2 / numel(clean_tensor);
    gaussian_sigma = sqrt( ...
        signal_power / 10^(settings.snr_db / 10));
    stream = RandStream('mt19937ar', 'Seed', seeds.gaussian);
    observed_full = clean_tensor + gaussian_sigma * ...
        randn(stream, rows, cols, total_frames);

    stream = RandStream('mt19937ar', 'Seed', seeds.spatter);
    spatter_mask = rand(stream, rows, cols, total_frames) < ...
        settings.spatter_density;
    num_spatter = nnz(spatter_mask);
    observed_full(spatter_mask) = observed_full(spatter_mask) + ...
        settings.spatter_base_magnitude * ...
        (1 + abs(randn(stream, num_spatter, 1)));

    stream = RandStream('mt19937ar', 'Seed', seeds.observation);
    observation_mask = rand(stream, rows, cols, total_frames) < ...
        settings.observation_ratio;
    observed_tensor = observed_full .* observation_mask;

    stream = RandStream('mt19937ar', 'Seed', seeds.side_delay);
    side_delay = randi(stream, settings.side_delay_range, 1, 1);
    side_event_start = settings.transition_boundary + side_delay;
    side_event = zeros(total_frames, 1);
    side_event(side_event_start) = ...
        settings.side_event_gain * settings.mutation_scale;
    for frame = side_event_start + 1:total_frames
        side_event(frame) = settings.side_event_decay * ...
            side_event(frame - 1);
    end
    stream = RandStream('mt19937ar', 'Seed', seeds.side_noise);
    side_signal = settings.side_baseline + side_event + ...
        settings.side_noise_sigma * ...
        randn(stream, total_frames, 1);

    stream = RandStream('mt19937ar', 'Seed', seeds.initialization);
    initialization.A = orthonormalize_with_sign( ...
        randn(stream, rows, max_estimated_rank));
    initialization.B = orthonormalize_with_sign( ...
        randn(stream, cols, max_estimated_rank));
    initialization.C = randn( ...
        stream, total_frames, max_estimated_rank);

    visual_sigma = estimate_visual_sigma( ...
        observed_tensor, observation_mask, settings.burn_in_frames);
    side_sigma = estimate_side_sigma( ...
        side_signal, settings.burn_in_frames);

    trial_data.clean_tensor = clean_tensor;
    trial_data.observed_tensor = observed_tensor;
    trial_data.observation_mask = observation_mask;
    trial_data.side_signal = side_signal;
    trial_data.initialization = initialization;
    trial_data.visual_sigma = visual_sigma;
    trial_data.side_sigma = side_sigma;
    trial_data.side_delay = side_delay;
    trial_data.actual_spatter_density = ...
        num_spatter / numel(spatter_mask);
    trial_data.transition_boundary = settings.transition_boundary;
end

function basis = orthonormalize_with_sign(input_matrix)
    [q_matrix, r_matrix] = qr(input_matrix, 0);
    signs = sign(diag(r_matrix) + 1e-10);
    basis = q_matrix * diag(signs);
end

function sigma = estimate_visual_sigma( ...
    observed_tensor, observation_mask, burn_in_frames)

    differences = cell(burn_in_frames - 1, 1);
    for frame = 2:burn_in_frames
        common_mask = observation_mask(:, :, frame) & ...
            observation_mask(:, :, frame - 1);
        frame_difference = observed_tensor(:, :, frame) - ...
            observed_tensor(:, :, frame - 1);
        differences{frame - 1} = frame_difference(common_mask);
    end
    differences = vertcat(differences{:});
    if isempty(differences)
        error('Exp_S6:UnavailableVisualScale', ...
            'No common observed pixels are available during burn-in.');
    end

    center = median(differences);
    mad_value = median(abs(differences - center));
    sigma = (1.4826 * mad_value) / sqrt(2);
    if ~isfinite(sigma) || sigma <= 0
        error('Exp_S6:InvalidVisualScale', ...
            'The burn-in visual scale estimate is not positive and finite.');
    end
end

function sigma = estimate_side_sigma(side_signal, burn_in_frames)
    differences = diff(side_signal(1:burn_in_frames));
    center = median(differences);
    mad_value = median(abs(differences - center));
    sigma = (1.4826 * mad_value) / sqrt(2);
    if ~isfinite(sigma) || sigma <= 0
        error('Exp_S6:InvalidSideScale', ...
            'The burn-in side-information scale is not positive and finite.');
    end
end

function [nre_curve, lambda_curve, metrics, elapsed] = ...
    run_s6_configuration(trial_data, configuration, initialization, ...
    huber_delta, side_threshold, irls_tolerance, ...
    normalization_epsilon, metric_names, trial)

    tensor_dims = size(trial_data.clean_tensor);
    options = struct( ...
        'lambda_min', configuration.lambda_min, ...
        'lambda_max', configuration.lambda_max, ...
        'huber_delta', huber_delta, ...
        'min_grad_threshold', side_threshold, ...
        'mu', configuration.mu, ...
        'grad_ema_alpha', configuration.grad_ema_alpha, ...
        'irls_max_iters', configuration.irls_max_iters, ...
        'irls_tolerance', irls_tolerance, ...
        'normalization_epsilon', normalization_epsilon, ...
        'verbose', 0, ...
        'early_stop_on', 'none', ...
        'store_matrix', true, ...
        'store_subinfo', false);

    timer = tic;
    [~, ~, information] = rsi_olstec( ...
        trial_data.observed_tensor, trial_data.observation_mask, [], ...
        tensor_dims, configuration.estimated_rank, initialization, ...
        options, trial_data.side_signal);
    elapsed = toc(timer);

    nre_curve = validate_complete_nre( ...
        compute_true_nre_tensor( ...
        trial_data.clean_tensor, information.L), ...
        tensor_dims(3), configuration.id, trial);
    nre_curve = nre_curve(:)';

    lambda_curve = information.lambda_history(:)';
    if numel(lambda_curve) ~= tensor_dims(3) || ...
            any(~isfinite(lambda_curve))
        error('Exp_S6:InvalidLambdaHistory', ...
            'The forgetting-factor history is incomplete or non-finite.');
    end
    tolerance = 1e-12;
    if any(lambda_curve < configuration.lambda_min - tolerance) || ...
            any(lambda_curve > configuration.lambda_max + tolerance)
        error('Exp_S6:InvalidLambdaHistory', ...
            'The forgetting factor lies outside its configured bounds.');
    end

    prior_iterations = information.prior_irls_iterations(:);
    posterior_iterations = information.posterior_irls_iterations(:);
    if numel(prior_iterations) ~= tensor_dims(3) || ...
            numel(posterior_iterations) ~= tensor_dims(3) || ...
            any(~isfinite(prior_iterations)) || ...
            any(~isfinite(posterior_iterations))
        error('Exp_S6:InvalidIRLSHistory', ...
            'The IRLS iteration histories are incomplete or non-finite.');
    end

    metrics = compute_s6_metrics( ...
        nre_curve, lambda_curve, prior_iterations, ...
        posterior_iterations, trial_data.transition_boundary);
    if numel(metrics) ~= numel(metric_names) || any(~isfinite(metrics))
        error('Exp_S6:InvalidMetrics', ...
            'The parameter-sensitivity metrics are incomplete or non-finite.');
    end
end

function metrics = compute_s6_metrics( ...
    nre_curve, lambda_curve, prior_iterations, ...
    posterior_iterations, transition_boundary)

    total_frames = numel(nre_curve);
    pre_50 = (transition_boundary - 50):(transition_boundary - 1);
    post_50 = transition_boundary:(transition_boundary + 49);
    final_100 = (total_frames - 99):total_frames;

    metrics = [ ...
        mean(nre_curve(pre_50)), ...
        sum(nre_curve(post_50)), ...
        mean(nre_curve(final_100)), ...
        mean(lambda_curve), ...
        min(lambda_curve(post_50)), ...
        mean(prior_iterations), ...
        mean(posterior_iterations)];
end

function record = make_failure_record( ...
    trial, trial_seed, configuration_id, exception)

    identifier = exception.identifier;
    if isempty(identifier)
        identifier = 'unidentified_exception';
    end
    message_text = regexprep( ...
        strtrim(exception.message), '[\r\n]+', ' | ');
    record = struct( ...
        'Trial', trial, ...
        'TrialSeed', trial_seed, ...
        'ConfigurationID', configuration_id, ...
        'Identifier', identifier, ...
        'Message', message_text);
end

function value = is_process_interruption(exception)
    diagnostic_text = lower([exception.identifier, ' ', exception.message]);
    value = contains(diagnostic_text, 'operationterminatedbyuser') || ...
        contains(diagnostic_text, 'terminated by user') || ...
        contains(diagnostic_text, 'operation terminated') || ...
        contains(diagnostic_text, 'nomem') || ...
        contains(diagnostic_text, 'outofmemory') || ...
        contains(diagnostic_text, 'out of memory') || ...
        contains(diagnostic_text, 'memory allocation') || ...
        contains(diagnostic_text, 'requested array exceeds') || ...
        contains(diagnostic_text, 'unable to allocate');
end

function [per_trial_table, summary_table] = build_s6_tables( ...
    state, configurations, metric_names, trial_seed_ids, ...
    ci_level, bootstrap_resamples)

    num_configurations = numel(configurations);
    num_trials = numel(trial_seed_ids);
    num_rows = num_configurations * num_trials;
    metric_index = @(name) find(strcmp(metric_names, name), 1);

    Trial = zeros(num_rows, 1);
    TrialSeed = zeros(num_rows, 1);
    ConfigurationID = cell(num_rows, 1);
    ParameterFamily = cell(num_rows, 1);
    ParameterValue = NaN(num_rows, 1);
    LambdaMin = NaN(num_rows, 1);
    LambdaMax = NaN(num_rows, 1);
    HuberScaleMultiplier = NaN(num_rows, 1);
    HuberDelta = NaN(num_rows, 1);
    Alpha = NaN(num_rows, 1);
    SideThresholdMultiplier = NaN(num_rows, 1);
    SideThreshold = NaN(num_rows, 1);
    Mu = NaN(num_rows, 1);
    EstimatedRank = NaN(num_rows, 1);
    IRLSMaxIterations = NaN(num_rows, 1);
    Status = zeros(num_rows, 1, 'uint8');
    ExecutionPosition = NaN(num_rows, 1);
    RuntimeSeconds = NaN(num_rows, 1);
    PreMutationMeanNRE50 = NaN(num_rows, 1);
    RecoveryIntegral50 = NaN(num_rows, 1);
    FinalMeanNRE100 = NaN(num_rows, 1);
    MeanLambda = NaN(num_rows, 1);
    MinimumLambdaPost50 = NaN(num_rows, 1);
    MeanPriorIRLSIterations = NaN(num_rows, 1);
