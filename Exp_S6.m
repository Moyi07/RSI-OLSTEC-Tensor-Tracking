            320000 + configuration_index);
        [FinalMeanNRE100DifferenceMean(configuration_index), ...
            FinalMeanNRE100DifferenceCILower(configuration_index), ...
            FinalMeanNRE100DifferenceCIUpper(configuration_index)] = ...
            summarize_difference(final_difference, ...
            bootstrap_resamples, ci_level, ...
            330000 + configuration_index);

        runtime_values = state.runtime_seconds( ...
            configuration_index, valid);
        RuntimeMedianSeconds(configuration_index) = ...
            finite_median(runtime_values);
