            FinalMeanNRE100CILower(configuration_index), ...
            FinalMeanNRE100CIUpper(configuration_index)] = ...
            summarize_with_ci(final_values(valid), ...
            bootstrap_resamples, ci_level, ...
            310000 + configuration_index);

        paired = valid & default_valid & ...
            isfinite(recovery_values) & isfinite(default_recovery) & ...
