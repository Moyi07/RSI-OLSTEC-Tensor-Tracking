    ActualObservationRatio = NaN(num_rows, 1);
    ActualSpatterDensity = NaN(num_rows, 1);
    SideDelay = NaN(num_rows, 1);

    row = 0;
    for trial = 1:num_trials
        for configuration_index = 1:num_configurations
            row = row + 1;
            configuration = configurations(configuration_index);
            Trial(row) = trial;
            TrialSeed(row) = trial_seed_ids(trial);
            ConfigurationID{row} = configuration.id;
            ParameterFamily{row} = configuration.parameter_family;
            ParameterValue(row) = configuration.parameter_value;
            LambdaMin(row) = configuration.lambda_min;
            LambdaMax(row) = configuration.lambda_max;
            HuberScaleMultiplier(row) = ...
                configuration.huber_scale_multiplier;
            HuberDelta(row) = ...
                state.huber_delta(configuration_index, trial);
            Alpha(row) = configuration.grad_ema_alpha;
            SideThresholdMultiplier(row) = ...
                configuration.side_threshold_multiplier;
            SideThreshold(row) = ...
                state.side_threshold(configuration_index, trial);
            Mu(row) = configuration.mu;
            EstimatedRank(row) = configuration.estimated_rank;
            IRLSMaxIterations(row) = configuration.irls_max_iters;
            Status(row) = state.status(configuration_index, trial);
            ExecutionPosition(row) = ...
                state.execution_position(configuration_index, trial);
            RuntimeSeconds(row) = ...
                state.runtime_seconds(configuration_index, trial);
            PreMutationMeanNRE50(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('PreMutationMeanNRE50'));
            RecoveryIntegral50(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('RecoveryIntegral50'));
            FinalMeanNRE100(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('FinalMeanNRE100'));
            MeanLambda(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('MeanLambda'));
            MinimumLambdaPost50(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('MinimumLambdaPost50'));
            MeanPriorIRLSIterations(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('MeanPriorIRLSIterations'));
            MeanPosteriorIRLSIterations(row) = state.metrics( ...
                configuration_index, trial, ...
                metric_index('MeanPosteriorIRLSIterations'));
            VisualSigma(row) = state.visual_sigma(trial);
            SideSigma(row) = state.side_sigma(trial);
            ActualObservationRatio(row) = ...
                state.actual_observation_ratio(trial);
            ActualSpatterDensity(row) = ...
                state.actual_spatter_density(trial);
            SideDelay(row) = state.side_delay(trial);
        end
    end

    per_trial_table = table( ...
        Trial, TrialSeed, ConfigurationID, ParameterFamily, ...
        ParameterValue, LambdaMin, LambdaMax, ...
        HuberScaleMultiplier, HuberDelta, Alpha, ...
        SideThresholdMultiplier, SideThreshold, Mu, EstimatedRank, ...
        IRLSMaxIterations, Status, ExecutionPosition, RuntimeSeconds, ...
        PreMutationMeanNRE50, RecoveryIntegral50, FinalMeanNRE100, ...
        MeanLambda, MinimumLambdaPost50, MeanPriorIRLSIterations, ...
        MeanPosteriorIRLSIterations, VisualSigma, SideSigma, ...
        ActualObservationRatio, ActualSpatterDensity, SideDelay);

    ConfigurationID = {configurations.id}';
    Label = {configurations.label}';
    ParameterFamily = {configurations.parameter_family}';
    ParameterValue = [configurations.parameter_value]';
    SuccessfulRuns = zeros(num_configurations, 1);
    FailedRuns = zeros(num_configurations, 1);
    PairedRuns = zeros(num_configurations, 1);

    PreMutationMeanNRE50Mean = NaN(num_configurations, 1);
    RecoveryIntegral50Mean = NaN(num_configurations, 1);
    RecoveryIntegral50Std = NaN(num_configurations, 1);
    RecoveryIntegral50CILower = NaN(num_configurations, 1);
    RecoveryIntegral50CIUpper = NaN(num_configurations, 1);
    RecoveryIntegral50DifferenceMean = NaN(num_configurations, 1);
    RecoveryIntegral50DifferenceCILower = NaN(num_configurations, 1);
    RecoveryIntegral50DifferenceCIUpper = NaN(num_configurations, 1);
    FinalMeanNRE100Mean = NaN(num_configurations, 1);
    FinalMeanNRE100Std = NaN(num_configurations, 1);
    FinalMeanNRE100CILower = NaN(num_configurations, 1);
    FinalMeanNRE100CIUpper = NaN(num_configurations, 1);
    FinalMeanNRE100DifferenceMean = NaN(num_configurations, 1);
    FinalMeanNRE100DifferenceCILower = NaN(num_configurations, 1);
    FinalMeanNRE100DifferenceCIUpper = NaN(num_configurations, 1);
    RuntimeMedianSeconds = NaN(num_configurations, 1);
    RuntimeIQRSeconds = NaN(num_configurations, 1);
    MeanLambdaMean = NaN(num_configurations, 1);
    MinimumLambdaPost50Mean = NaN(num_configurations, 1);
    MeanPriorIRLSIterationsMean = NaN(num_configurations, 1);
    MeanPosteriorIRLSIterationsMean = NaN(num_configurations, 1);
    HuberDeltaMean = NaN(num_configurations, 1);
    SideThresholdMean = NaN(num_configurations, 1);

