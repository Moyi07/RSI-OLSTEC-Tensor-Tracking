%% Experiment S6: Parameter sensitivity of RSI-OLSTEC
% Paired one-factor-at-a-time sensitivity analysis under a common
% synthetic tracking scenario with impulsive corruption and one abrupt
% structural mutation.
clear; clc; close all;

repo_root = fileparts(mfilename('fullpath'));
addpath(repo_root);
addpath(genpath(fullfile(repo_root, 'tool')));
addpath(genpath(fullfile(repo_root, 'auxiliary')));
addpath(genpath(fullfile(repo_root, 'benchmark')));

%% 1. Experimental configuration
num_trials = 50;
trial_seed_ids = (2001:(2000 + num_trials))';

data_settings = struct( ...
    'tensor_dims', [50, 50, 500], ...
    'true_rank', 5, ...
    'transition_boundary', 251, ...
    'mutation_scale', 0.50, ...
    'snr_db', 25, ...
    'spatter_density', 0.05, ...
    'spatter_base_magnitude', 0.50, ...
    'observation_ratio', 0.50, ...
    'side_baseline', 10.0, ...
    'side_event_gain', 10.0, ...
    'side_event_decay', 0.80, ...
    'side_noise_sigma', 0.20, ...
    'side_delay_range', [2, 5], ...
    'burn_in_frames', 30, ...
    'huber_delta_lower_bound', 0.01, ...
    'side_threshold_floor', 0.05);

default_config = struct( ...
    'id', 'default', ...
    'label', 'Default', ...
    'parameter_family', 'default', ...
    'parameter_value', NaN, ...
    'lambda_min', 0.70, ...
    'lambda_max', 0.80, ...
    'huber_scale_multiplier', 3.0, ...
    'grad_ema_alpha', 0.999, ...
    'side_threshold_multiplier', 3.0, ...
    'mu', 0.01, ...
    'estimated_rank', 5, ...
    'irls_max_iters', 3);

parameter_values = struct( ...
    'lambda_min', [0.10, 0.40, 0.70], ...
    'lambda_max', [0.80, 0.90, 0.99], ...
    'huber_scale_multiplier', [1.345, 3.0, 6.0], ...
    'grad_ema_alpha', [0.90, 0.99, 0.999], ...
    'side_threshold_multiplier', [1.0, 3.0, 6.0], ...
    'mu', [1e-3, 1e-2, 1e-1], ...
    'estimated_rank', [3, 5, 7], ...
    'irls_max_iters', [1, 3, 5]);

configurations = define_s6_configurations( ...
    default_config, parameter_values);
num_configurations = numel(configurations);
max_estimated_rank = max([configurations.estimated_rank]);

irls_tolerance = 1e-3;
normalization_epsilon = 1e-3;
ci_level = 0.95;
bootstrap_resamples = 10000;
export_results = true;

metric_names = { ...
    'PreMutationMeanNRE50', ...
    'RecoveryIntegral50', ...
    'FinalMeanNRE100', ...
    'MeanLambda', ...
    'MinimumLambdaPost50', ...
    'MeanPriorIRLSIterations', ...
    'MeanPosteriorIRLSIterations'};

result_dir = fullfile(repo_root, 'result', 'S6');
checkpoint_file = fullfile(result_dir, 'S6_checkpoint.mat');
if export_results && ~exist(result_dir, 'dir')
    mkdir(result_dir);
end

settings = struct( ...
    'num_trials', num_trials, ...
    'trial_seed_ids', trial_seed_ids, ...
    'data', data_settings, ...
    'default_config', default_config, ...
    'parameter_values', parameter_values, ...
    'configurations', configurations, ...
    'irls_tolerance', irls_tolerance, ...
    'normalization_epsilon', normalization_epsilon, ...
    'ci_level', ci_level, ...
    'bootstrap_resamples', bootstrap_resamples);

%% 2. Result storage and checkpoint
total_frames = data_settings.tensor_dims(3);
num_metrics = numel(metric_names);

state.completed_trials = false(num_trials, 1);
state.status = zeros(num_configurations, num_trials, 'uint8');
state.metrics = NaN(num_configurations, num_trials, num_metrics);
state.runtime_seconds = NaN(num_configurations, num_trials);
state.nre_curves = NaN(num_configurations, num_trials, total_frames);
state.lambda_curves = NaN(num_configurations, num_trials, total_frames);
state.huber_delta = NaN(num_configurations, num_trials);
state.side_threshold = NaN(num_configurations, num_trials);
state.visual_sigma = NaN(num_trials, 1);
state.side_sigma = NaN(num_trials, 1);
state.actual_observation_ratio = NaN(num_trials, 1);
state.actual_spatter_density = NaN(num_trials, 1);
state.side_delay = NaN(num_trials, 1);
state.execution_position = NaN(num_configurations, num_trials);
state.failure_records = struct( ...
    'Trial', {}, 'TrialSeed', {}, 'ConfigurationID', {}, ...
    'Identifier', {}, 'Message', {});

if exist(checkpoint_file, 'file')
    loaded = load(checkpoint_file, 'checkpoint');
    if ~isfield(loaded, 'checkpoint') || ...
            ~isequaln(loaded.checkpoint.settings, settings)
        error('Exp_S6:CheckpointMismatch', ...
            'The existing S6 checkpoint uses different settings.');
    end
    state = loaded.checkpoint.state;
    fprintf('Resuming S6 from %d/%d completed trials.\n', ...
        nnz(state.completed_trials), num_trials);
end

%% 3. Paired Monte Carlo sensitivity analysis
fprintf(['Starting S6 with %d paired trials and %d unique parameter ', ...
    'configurations per trial.\n'], num_trials, num_configurations);

for trial = 1:num_trials
    if state.completed_trials(trial)
        continue;
    end

    trial_seed = trial_seed_ids(trial);
    fprintf('Trial %d/%d (seed %d)\n', trial, num_trials, trial_seed);

    seeds = make_s6_seeds(trial_seed);
    trial_data = generate_s6_trial( ...
        data_settings, seeds, max_estimated_rank);

    state.visual_sigma(trial) = trial_data.visual_sigma;
    state.side_sigma(trial) = trial_data.side_sigma;
    state.actual_observation_ratio(trial) = ...
        nnz(trial_data.observation_mask) / ...
        numel(trial_data.observation_mask);
    state.actual_spatter_density(trial) = ...
        trial_data.actual_spatter_density;
    state.side_delay(trial) = trial_data.side_delay;

    execution_stream = RandStream( ...
        'mt19937ar', 'Seed', seeds.execution_order);
    [~, execution_order] = sort( ...
        rand(execution_stream, num_configurations, 1));

    for execution_position = 1:num_configurations
        configuration_index = execution_order(execution_position);
        configuration = configurations(configuration_index);
        state.execution_position(configuration_index, trial) = ...
            execution_position;

        huber_delta = max( ...
            data_settings.huber_delta_lower_bound, ...
            configuration.huber_scale_multiplier * ...
            trial_data.visual_sigma);
        side_threshold = max( ...
            data_settings.side_threshold_floor, ...
            configuration.side_threshold_multiplier * sqrt(2) * ...
            trial_data.side_sigma);
        state.huber_delta(configuration_index, trial) = huber_delta;
        state.side_threshold(configuration_index, trial) = ...
            side_threshold;

        rank_r = configuration.estimated_rank;
        initialization = struct( ...
            'A', trial_data.initialization.A(:, 1:rank_r), ...
            'B', trial_data.initialization.B(:, 1:rank_r), ...
            'C', trial_data.initialization.C(:, 1:rank_r));

        try
            [nre_curve, lambda_curve, metrics, elapsed] = ...
                run_s6_configuration(trial_data, configuration, ...
                initialization, huber_delta, side_threshold, ...
                irls_tolerance, normalization_epsilon, metric_names, ...
                trial);

            state.status(configuration_index, trial) = uint8(1);
            state.metrics(configuration_index, trial, :) = ...
                reshape(metrics, 1, 1, []);
            state.runtime_seconds(configuration_index, trial) = elapsed;
            state.nre_curves(configuration_index, trial, :) = ...
                reshape(nre_curve, 1, 1, []);
            state.lambda_curves(configuration_index, trial, :) = ...
                reshape(lambda_curve, 1, 1, []);

            fprintf('  %-24s %8.2f s\n', ...
                configuration.id, elapsed);
        catch exception
            if is_process_interruption(exception)
                rethrow(exception);
            end

            state.status(configuration_index, trial) = uint8(2);
            state.failure_records(end + 1) = make_failure_record( ...
                trial, trial_seed, configuration.id, exception);
            fprintf('  %-24s failed: %s\n', ...
                configuration.id, exception.message);
        end
    end

    state.completed_trials(trial) = true;
    if export_results
        checkpoint = struct('settings', settings, 'state', state);
        save_checkpoint_atomic(checkpoint_file, checkpoint);
        clear checkpoint;
    end
    clear trial_data;
end

