function plot_s6_metric(summary_table, configurations, metric_name, ...
    y_label, file_name, result_dir, export_results)

    families = {'lambda_min', 'lambda_max', 'huber', 'alpha', ...
        'theta', 'mu', 'rank', 'irls'};
    family_titles = {'$\lambda_{\min}$', '$\lambda_{\max}$', ...
        'Huber multiplier', '$\alpha$', 'Dead-zone multiplier', ...
        '$\mu$', 'Estimated rank', 'IRLS iterations'};
    mean_values = summary_table.([metric_name, 'Mean']);
    lower_values = summary_table.([metric_name, 'CILower']);
    upper_values = summary_table.([metric_name, 'CIUpper']);
    default_index = find(strcmp({configurations.id}, 'default'), 1);

    figure_handle = figure( ...
        'Color', 'w', 'Visible', 'off', ...
        'Position', [80, 80, 1500, 720]);

    for family_index = 1:numel(families)
        family = families{family_index};
        axes_handle = subplot(2, 4, family_index, ...
            'Parent', figure_handle);
        hold(axes_handle, 'on');
        box(axes_handle, 'on');
        grid(axes_handle, 'on');

        family_indices = find(strcmp( ...
            {configurations.parameter_family}, family));
        configuration_indices = [default_index, family_indices];
        parameter_axis = zeros(size(configuration_indices));
        for value_index = 1:numel(configuration_indices)
            parameter_axis(value_index) = family_parameter_value( ...
                configurations(configuration_indices(value_index)), ...
                family);
        end
        [parameter_axis, order] = sort(parameter_axis);
        configuration_indices = configuration_indices(order);

        plotted_means = mean_values(configuration_indices);
        lower_errors = plotted_means - ...
            lower_values(configuration_indices);
        upper_errors = upper_values(configuration_indices) - ...
            plotted_means;
        errorbar(axes_handle, parameter_axis, plotted_means, ...
            lower_errors, upper_errors, '-o', ...
            'Color', [0.15, 0.40, 0.70], ...
            'MarkerFaceColor', [0.15, 0.40, 0.70], ...
            'LineWidth', 1.3, 'MarkerSize', 6, 'CapSize', 7);

        default_x = family_parameter_value( ...
            configurations(default_index), family);
        plot(axes_handle, default_x, mean_values(default_index), ...
            's', 'Color', [0.75, 0.20, 0.15], ...
            'MarkerFaceColor', [0.75, 0.20, 0.15], ...
            'MarkerSize', 7);

        if strcmp(family, 'mu')
            set(axes_handle, 'XScale', 'log');
        end
        title(axes_handle, family_titles{family_index}, ...
            'Interpreter', 'latex');
        xlabel(axes_handle, 'Parameter value');
        ylabel(axes_handle, y_label);
        set(axes_handle, ...
            'FontName', 'Times New Roman', 'FontSize', 10);
    end

    if export_results
        set(figure_handle, 'Visible', 'on');
        savefig(figure_handle, fullfile(result_dir, [file_name, '.fig']));
        set(figure_handle, 'Visible', 'off');
        set(figure_handle, 'Units', 'Inches');
        position = get(figure_handle, 'Position');
        set(figure_handle, ...
            'PaperPositionMode', 'auto', ...
            'PaperUnits', 'Inches', ...
            'PaperSize', [position(3), position(4)]);
        print(figure_handle, fullfile(result_dir, [file_name, '.pdf']), ...
            '-dpdf', '-vector');
        print(figure_handle, fullfile(result_dir, [file_name, '.eps']), ...
            '-depsc', '-vector');
    end
    close(figure_handle);
end

function value = family_parameter_value(configuration, family)
    switch family
        case 'lambda_min'
            value = configuration.lambda_min;
        case 'lambda_max'
            value = configuration.lambda_max;
        case 'huber'
            value = configuration.huber_scale_multiplier;
        case 'alpha'
            value = configuration.grad_ema_alpha;
        case 'theta'
            value = configuration.side_threshold_multiplier;
        case 'mu'
            value = configuration.mu;
        case 'rank'
            value = configuration.estimated_rank;
        case 'irls'
            value = configuration.irls_max_iters;
        otherwise
            error('Exp_S6:UnknownParameterFamily', ...
                'Unknown parameter family: %s.', family);
    end
end
