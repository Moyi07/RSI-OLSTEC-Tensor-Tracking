        state.metrics(1, :, final_index), [], 1);
    default_valid = state.status(1, :)' == 1;

    for configuration_index = 1:num_configurations
        valid = state.status(configuration_index, :)' == 1;
        SuccessfulRuns(configuration_index) = nnz(valid);
        FailedRuns(configuration_index) = nnz( ...
            state.status(configuration_index, :)' == 2);

        pre_values = reshape(state.metrics( ...
            configuration_index, :, ...
            metric_index('PreMutationMeanNRE50')), [], 1);
        recovery_values = reshape(state.metrics( ...
            configuration_index, :, recovery_index), [], 1);
