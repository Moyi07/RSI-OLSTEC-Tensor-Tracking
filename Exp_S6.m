        RecoveryIntegral50Mean, RecoveryIntegral50Std, ...
        RecoveryIntegral50CILower, RecoveryIntegral50CIUpper, ...
        RecoveryIntegral50DifferenceMean, ...
        RecoveryIntegral50DifferenceCILower, ...
        RecoveryIntegral50DifferenceCIUpper, ...
        FinalMeanNRE100Mean, FinalMeanNRE100Std, ...
        FinalMeanNRE100CILower, FinalMeanNRE100CIUpper, ...
        FinalMeanNRE100DifferenceMean, ...
        FinalMeanNRE100DifferenceCILower, ...
        FinalMeanNRE100DifferenceCIUpper, ...
        RuntimeMedianSeconds, RuntimeIQRSeconds, ...
        MeanLambdaMean, MinimumLambdaPost50Mean, ...
        MeanPriorIRLSIterationsMean, ...
        MeanPosteriorIRLSIterationsMean, ...
        HuberDeltaMean, SideThresholdMean);
end

function [mean_value, std_value, lower, upper] = ...
    summarize_with_ci(values, num_resamples, ci_level, seed)

    values = values(isfinite(values));
    if isempty(values)
        mean_value = NaN;
        std_value = NaN;
        lower = NaN;
        upper = NaN;
        return;
    end
    mean_value = mean(values);
    std_value = std(values, 0);
    [lower, upper] = bootstrap_mean_ci( ...
        values, num_resamples, ci_level, seed);
end

function [mean_value, lower, upper] = summarize_difference( ...
    values, num_resamples, ci_level, seed)

    values = values(isfinite(values));
    if isempty(values)
        mean_value = NaN;
        lower = NaN;
        upper = NaN;
        return;
    end
    mean_value = mean(values);
    [lower, upper] = bootstrap_mean_ci( ...
        values, num_resamples, ci_level, seed);
end

function [lower, upper] = bootstrap_mean_ci( ...
    values, num_resamples, ci_level, seed)

    values = values(:);
    if numel(values) < 2
        lower = NaN;
        upper = NaN;
        return;
    end

    stream = RandStream('mt19937ar', 'Seed', seed);
    indices = randi( ...
        stream, numel(values), numel(values), num_resamples);
    bootstrap_means = sort(mean(values(indices), 1));
    tail = (1 - ci_level) / 2;
    lower = linear_quantile(bootstrap_means, tail);
    upper = linear_quantile(bootstrap_means, 1 - tail);
end

function value = finite_mean(values)
    values = values(isfinite(values));
    if isempty(values)
        value = NaN;
    else
        value = mean(values);
    end
end

function value = finite_median(values)
    values = values(isfinite(values));
    if isempty(values)
        value = NaN;
    else
        value = median(values);
    end
end

function value = finite_iqr(values)
    values = sort(values(isfinite(values)));
    if isempty(values)
        value = NaN;
    else
        value = linear_quantile(values, 0.75) - ...
            linear_quantile(values, 0.25);
    end
end

function value = linear_quantile(sorted_values, probability)
    sorted_values = sorted_values(:);
    position = 1 + (numel(sorted_values) - 1) * probability;
    lower_index = floor(position);
    upper_index = ceil(position);
    if lower_index == upper_index
        value = sorted_values(lower_index);
    else
        weight = position - lower_index;
        value = sorted_values(lower_index) + weight * ...
            (sorted_values(upper_index) - sorted_values(lower_index));
    end
end

